# One Word From Grandma
#
# This program writes exactly one word to standard output.
# It takes no input, reads no files, and uses no randomness,
# so every run produces exactly the same single word.
#
# The word lives in the print statement below and nowhere else.
# Nothing is printed before it and nothing after it.
# The process ends normally right after the word appears.
# One noun, spoken like a whole sentence: food is ready,
# there is plenty, and nobody leaves hungry.
# Run it with: python3 main.py
# Exactly one word on stdout.
print("Leftovers.")
